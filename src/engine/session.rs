#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::SquirrelConfig;
    use crate::types::{FusedScore, Location, RedactedString, Severity};
    use chrono::Utc;

    fn dummy_finding(rule_id: &str, path: &str, severity: Severity, confidence: f64) -> Finding {
        Finding {
            id: uuid_stub(rule_id, path),
            rule_id: rule_id.to_string(),
            description: format!("Test finding for {rule_id}"),
            secret: RedactedString::new("AKIAIOSFODNN7EXAMPLE".to_string()),
            secret_hash: format!("{rule_id}:{path}:hash"),
            match_context: String::new(),
            location: Location {
                path: path.to_string(),
                start_line: 1,
                end_line: 1,
                start_col: 0,
                end_col: 20,
                byte_offset: 0,
            },
            score: FusedScore {
                confidence,
                entropy: 0.5,
                proximity: 0.5,
                tristream: 0.5,
                pattern: 0.5,
                markov: 0.5,
                cnn_score: None,
                ast_adjustment: None,
            },
            severity,
            chain: None,
            validation: None,
            remediation: None,
            detected_at: Utc::now(), encoding_chain: None,
        }
    }

    /// Deterministic stub ID for testing.
    fn uuid_stub(rule: &str, path: &str) -> String {
        format!("{rule}_{path}")
    }

    #[test]
    fn test_new_session_generates_nonce() {
        let config = SquirrelConfig::default();
        let session = ScanSession::new(config);
        assert_eq!(session.nonce.len(), 32);
        assert_ne!(session.nonce, vec![0u8; 32], "Nonce should be random");
    }

    #[test]
    fn test_nonces_differ_across_sessions() {
        let s1 = ScanSession::new(SquirrelConfig::default());
        let s2 = ScanSession::new(SquirrelConfig::default());
        assert_ne!(
            s1.nonce, s2.nonce,
            "Each session should have a unique nonce"
        );
    }

    #[test]
    fn test_add_finding_increments_count() {
        let mut session = ScanSession::new(SquirrelConfig::default());
        assert_eq!(session.stats.findings_count, 0);
        session.add_finding(dummy_finding("aws-access-key", "config.env", Severity::High, 0.9));
        assert_eq!(session.stats.findings_count, 1);
        assert_eq!(session.findings.len(), 1);
    }

    #[test]
    fn test_deduplicate_removes_exact_duplicates() {
        let mut session = ScanSession::new(SquirrelConfig::default());

        let f1 = dummy_finding("rule-a", "file.py", Severity::High, 0.9);
        let f2 = dummy_finding("rule-a", "file.py", Severity::High, 0.9); // duplicate
        let f3 = dummy_finding("rule-b", "file.py", Severity::Medium, 0.6); // different rule

        session.add_finding(f1);
        session.add_finding(f2);
        session.add_finding(f3);

        assert_eq!(session.findings.len(), 3);
        session.deduplicate_findings();
        // f1 and f2 share (rule_id, secret_hash, path) → one removed
        assert_eq!(session.findings.len(), 2);
    }

    #[test]
    fn test_finalize_sorts_by_severity_desc() {
        let mut session = ScanSession::new(SquirrelConfig::default());

        session.add_finding(dummy_finding("rule-low", "a.py", Severity::Low, 0.6));
        session.add_finding(dummy_finding("rule-critical", "b.py", Severity::Critical, 0.95));
        session.add_finding(dummy_finding("rule-medium", "c.py", Severity::Medium, 0.7));

        session.finalize();

        assert_eq!(session.findings[0].severity, Severity::Critical);
        assert_eq!(session.findings[1].severity, Severity::Medium);
        assert_eq!(session.findings[2].severity, Severity::Low);
    }

    #[test]
    fn test_finalize_sorts_by_confidence_within_severity() {
        let mut session = ScanSession::new(SquirrelConfig::default());

        session.add_finding(dummy_finding("rule-a", "a.py", Severity::High, 0.6));
        session.add_finding(dummy_finding("rule-b", "b.py", Severity::High, 0.95));

        session.finalize();

        // Higher confidence should come first.
        assert!(
            session.findings[0].score.confidence >= session.findings[1].score.confidence,
            "Findings should be sorted by confidence descending"
        );
    }

    #[test]
    fn test_has_findings_at_or_above() {
        let mut session = ScanSession::new(SquirrelConfig::default());
        session.add_finding(dummy_finding("rule-a", "a.py", Severity::Medium, 0.7));

        assert!(session.has_findings_at_or_above(Severity::Low));
        assert!(session.has_findings_at_or_above(Severity::Medium));
        assert!(!session.has_findings_at_or_above(Severity::High));
    }

    #[test]
    fn test_stats_record_file() {
        let mut stats = ScanStats::new();
        stats.record_file(1024, false);
        stats.record_file(2048, true);

        assert_eq!(stats.files_scanned, 2);
        assert_eq!(stats.bytes_scanned, 3072);
        assert_eq!(stats.cpu_dispatches, 1);
        assert_eq!(stats.gpu_dispatches, 1);
        assert_eq!(stats.total_dispatches(), 2);
    }

    #[test]
    fn test_stats_gpu_utilisation() {
        let mut stats = ScanStats::new();
        stats.record_file(1000, true);
        stats.record_file(1000, true);
        stats.record_file(1000, false);

        let util = stats.gpu_utilisation();
        assert!(
            (util - 2.0 / 3.0).abs() < 0.001,
            "GPU utilisation should be 2/3"
        );
    }

    #[test]
    fn test_filtered_findings_respects_threshold() {
        let mut config = SquirrelConfig::default();
        config.scan.severity_threshold = Severity::High;

        let mut session = ScanSession::new(config);
        session.add_finding(dummy_finding("low", "a.py", Severity::Low, 0.5));
        session.add_finding(dummy_finding("high", "b.py", Severity::High, 0.9));
        session.add_finding(dummy_finding("critical", "c.py", Severity::Critical, 0.99));

        let visible: Vec<_> = session.filtered_findings().collect();
        assert_eq!(visible.len(), 2, "Only High and Critical should be visible");
    }
}
